func base64Bytes(_ string: String) -> Bytes {
    guard let data = Data(base64Encoded: string) else {
        preconditionFailure("Invalid built-in base64 constant.")
    }
    return Bytes(data)
}

func hexBytes(_ string: String) -> Bytes {
    var output = Bytes()
    output.reserveCapacity(string.utf8.count / 2)
    var high: UInt8?
    for character in string.utf8 {
        let nibble: UInt8
        switch character {
        case 0x30...0x39: nibble = character - 0x30
        case 0x61...0x66: nibble = character - 0x61 + 10
        default: preconditionFailure("Invalid built-in hex constant.")
        }
        if let pending = high {
            output.append(pending << 4 | nibble)
            high = nil
        } else {
            high = nibble
        }
    }
    return output
}
